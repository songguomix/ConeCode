interface LanguageStore {
  locale: Locale;
  t: (key: string) => string;
  setLocale: (locale: Locale) => void;
}

const VALID_LOCALES: Locale[] = ['en', 'zh', 'zhHant', 'ja'];

function storedLocale(): Locale {
  const raw = (() => {
    try {
      return localStorage.getItem('locale');
    } catch {
      return null;
    }
  })();
  return (VALID_LOCALES as string[]).includes(raw || '') ? (raw as Locale) : 'en';
}

export const useLanguageStore = create<LanguageStore>((set, get) => ({
  locale: storedLocale(),
  // Traditional falls back to Simplified for any key the translation pass
  // missed, so the UI never shows a raw key.
  t: (key: string) =>
    translations[get().locale][key]
    || (get().locale === 'zhHant' ? translations.zh[key] : undefined)
    || key,
  setLocale: (locale) => {
    localStorage.setItem('locale', locale);
    set({ locale });
  },
}));
